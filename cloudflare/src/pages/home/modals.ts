  'function previewVersionBump(version, bump) {',
  '  const match = String(version || "").trim().match(/^v?(\\d+)\\.(\\d+)\\.(\\d+)$/i);',
  '  const normalized = match || [null, "1", "0", "0"];',
  '  const major = Number(normalized[1]);',
  '  const minor = Number(normalized[2]);',
  '  const patch = Number(normalized[3]);',
  '  if (bump === "major") return `${major + 1}.0.0`;',
  '  if (bump === "minor") return `${major}.${minor + 1}.0`;',
  '  return `${major}.${minor}.${patch + 1}`;',
  '}',
  '',
  'function inferVersionBump(baseVersion, targetVersion) {',
  '  return ["patch", "minor", "major"].find(bump => previewVersionBump(baseVersion, bump) === targetVersion) || "patch";',
