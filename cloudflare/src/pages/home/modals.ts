  'async function validateJsonUpload(file, kind) {',
  '  if (!file) return null;',
  '  if (!String(file.name || "").toLowerCase().endsWith(".json")) {',
  '    throw new Error(kind === "worldbook" ? "世界书文件必须是 .json" : "正则文件必须是 .json");',
  '  }',
  '  let parsed;',
  '  try {',
  '    parsed = JSON.parse(await file.text());',
  '  } catch {',
  '    throw new Error(kind === "worldbook" ? "世界书文件不是有效 JSON" : "正则文件不是有效 JSON");',
  '  }',
  '  if (kind === "worldbook") {',
  '    const entries = parsed && typeof parsed === "object" ? parsed.entries : null;',
  '    const recognized = Array.isArray(parsed) || Array.isArray(entries) || (entries && typeof entries === "object" && !Array.isArray(entries));',
  '    if (!recognized) {',
  '      throw new Error("世界书 JSON 格式不正确：需要条目数组，或包含 entries 数组/对象");',
  '    }',
  '  }',
  '  return parsed;',
  '}',
