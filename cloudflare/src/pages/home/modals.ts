  '  if (!file) return null;',
  '  assertUploadSize(file);',
  '  if (!String(file.name || "").toLowerCase().endsWith(".json")) {',
  '    throw new Error(kind === "worldbook" ? "世界书文件必须是 .json" : "正则文件必须是 .json");',
  '  }',
  '  let parsed;',
  '  try {',
  '    parsed = JSON.parse(await file.text());',
  '  } catch {',
  '    throw new Error(kind === "worldbook" ? "世界书文件不是有效 JSON" : "正则文件不是有效 JSON");',
  '  }',
  '  if (kind === "worldbook") {',
  '    const entries = parsed && typeof parsed === "object" ? parsed.entries : null;',
  '    const recognized = Boolean(parsed && typeof parsed === "object" && !Array.isArray(parsed) && (Array.isArray(entries) || (entries && typeof entries === "object" && !Array.isArray(entries))));',
  '    if (!recognized) {',
  '      throw new Error("世界书 JSON 格式不正确：需要 SillyTavern 世界书的顶层 entries");',
  '    }',
  '  }',
  '  if (kind === "worldbook") {',
  '    const entries = parsed.entries;',
  '    const values = Array.isArray(entries) ? entries : Object.values(entries);',
  '    if (!values.length || values.some(entry => !entry || typeof entry !== "object" || Array.isArray(entry))) {',
  '      throw new Error("世界书 JSON 格式不正确：entries 必须包含至少一个条目对象");',
  '    }',
  '  } else {',
  '    const regexEntries = Array.isArray(parsed) ? parsed : [parsed];',
  '    const validRegex = regexEntries.length > 0 && regexEntries.every(entry => entry && typeof entry === "object" && !Array.isArray(entry) && typeof entry.scriptName === "string" && entry.scriptName.trim());',
  '    if (!validRegex) {',
