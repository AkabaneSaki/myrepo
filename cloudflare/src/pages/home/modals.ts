  '  }',
  '  if (kind === "worldbook") {',
  '    const entries = parsed && typeof parsed === "object" ? parsed.entries : null;',
  '    const recognized = Array.isArray(parsed) || Array.isArray(entries) || (entries && typeof entries === "object" && !Array.isArray(entries));',
