  '      const looksLikeWorldbook = Array.isArray(worldbookEntries) || (worldbookEntries && typeof worldbookEntries === "object" && !Array.isArray(worldbookEntries));',
  '      throw new Error(looksLikeWorldbook ? "检测到世界书 JSON，请上传到世界书文件" : "正则 JSON 格式不正确：每个正则必须包含非空 scriptName");',
  '    }',
  '  }',
  '  return parsed;',
  '}',
