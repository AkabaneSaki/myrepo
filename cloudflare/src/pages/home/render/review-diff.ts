  "  const titles = unchanged.slice(0, 30).map(change => `<span>${escapeHtml(getAdminReviewChangeTitle(change, kind))}</span>`).join('');",
  "  const more = unchanged.length > 30 ? `<span>… 另外 ${unchanged.length - 30} 条</span>` : '';",
