import assert from 'node:assert/strict';
import { createHash, webcrypto } from 'node:crypto';
import { readFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { build } from 'esbuild';
import { contentFilesHash } from '../src/utils/ejs-checker/attestation.mjs';

// A source-only edit must never silently leave the deployed reviewer bundle stale.
const built = await build({
  entryPoints: [fileURLToPath(new URL('../src/utils/ejs-checker/review-worker.mjs', import.meta.url))],
  bundle: true, write: false, format: 'iife', platform: 'browser', target: 'es2022', minify: true,
  legalComments: 'none',
  banner: { js: '// Generated by cloudflare/scripts/build-review-checker.mjs. Licenses: /assets/upload-checker-notices.txt' },
});
const bundle = built.outputFiles[0].text;
const shipped = Buffer.from(
  await readFile(new URL('../src/generated/review-checker.txt', import.meta.url), 'utf8'),
  'base64',
).toString('utf8');
const revision = JSON.parse(await readFile(new URL('../src/generated/review-checker-revision.json', import.meta.url), 'utf8')).revision;
assert.equal(shipped, bundle, 'reviewer bundle is stale; run: node scripts/build-review-checker.mjs');
assert.equal(revision, createHash('sha256').update(shipped).digest('hex').slice(0, 20));

// Check the actual SHIPPED bundle, with a genuine >200k executable EJS unit.
const source = '<% const longText = "' + 'x'.repeat(200001) + '"; %>';
const files = [{ fileName: 'large-worldbook.json', type: 'worldbook',
  text: JSON.stringify({ entries: [{ uid: 7, comment: 'large executable', content: source }] }) }];
let received;
const self = { postMessage(message) { received = message; } };
new Function('self', 'crypto', shipped)(self, webcrypto);
assert.equal(typeof self.onmessage, 'function');
await self.onmessage({ data: { files, baseline: null, projectId: 'test-large',
  draftRevision: 2 } });
assert.equal(received?.success, true);
assert.equal(received?.gate, 'reject');
assert.ok(received.report.findings.some(item => item.ruleId === 'CHECKER-LIMIT'));
assert.match(received?.filesHash || '', /^[a-f0-9]{64}$/);
assert.equal(received?.filesHash, await contentFilesHash(files));
assert.equal(received?.auditSnapshot?.filesHash, received?.filesHash);
assert.ok(Array.isArray(received?.auditSnapshot?.findings));
console.log('Review bundle freshness and >200k CHECKER-LIMIT approval binding: ok');
