import assert from 'node:assert/strict';
import { parseEjs, parseRegex } from '../src/utils/ejs-checker/syntax.mjs';
import { inspectCapabilities } from '../src/utils/ejs-checker/capabilities.mjs';
const check=(code,type='ejs')=>inspectCapabilities({content:code},type==='ejs'?parseEjs(code):parseRegex(code)).map(f=>f.ruleId);
for(const code of ['eval("1")','(0,eval)("1")','globalThis["eval"]("1")','const alias=eval; alias("1")'])assert.ok(check('<% { '+code+' } %>').includes('M1'),code);
for(const code of ['new Function("1")','window.Function("1")','const alias=Function'])assert.ok(check('<% { '+code+' } %>').includes('M2'),code);
assert.deepEqual(check('<% { const eval=()=>1; eval(); const Function=()=>1; Function(); const text="eval(1)"; /* eval(1) */ } %>'),[]);
assert.deepEqual(check('<% { const object={eval(){return 1},Function(){return 1}}; object.eval(); } %>'),[]);
assert.ok(check('<% { document.cookie; localStorage.getItem("auth_token"); } %>').includes('M3'));
assert.deepEqual(check('<% { localStorage.getItem("qy18_theme"); localStorage.getItem("font_size"); } %>'),[]);
assert.ok(check('<% { fetch("/x"); } %>').includes('M4'));
assert.ok(check('<% { fetch(runtimeUrl); } %>').includes('U5'));
assert.ok(!check('<% { fetch.call(this,"/x"); } %>').includes('U5'));
assert.ok(check('<% { fetch.apply(this,[runtimeUrl]); } %>').includes('U5'));
for(const code of ['while(true){}','while(1){}','for(;;){}','for(let i=0;;i++){}'])assert.ok(check('<% { '+code+' } %>').includes('M5'),code);
assert.ok(check('<% for (;;) { %>').includes('M5'));
assert.ok(!check('<% { const text="while(true){}"; } %>').includes('M5'));
for(const [code,rule] of [['atob("1")','AH1'],['fn.call(null)','AH2'],['text.replace("<%= x %>","x")','AH3'],['document.createElement("script")','AH4']])assert.ok(check('<% { '+code+' } %>').includes(rule),rule);
assert.ok(check('<button onclick="ev&#97;l(&quot;1&quot;)">x</button>','regex').includes('M1'));
assert.deepEqual(check('<script type="application/json">{"eval":"x"}</script>','regex'),[]);
assert.deepEqual(check('<script type="module">import {fetch,eval,Function} from "x"; fetch(); eval(); Function();</script>','regex'),[]);
assert.deepEqual(check('<% { const fn=()=>`text ${eval("1")}`; } %>'),['M1']);
console.log('v2 common capabilities: AST references, executable regions and token evidence: ok');
