import { build } from 'esbuild';
import fs from 'node:fs/promises';
import { createHash } from 'node:crypto';
import { fileURLToPath } from 'node:url';

// Reviewer-device bundle for #42. The Worker never executes this rule analysis; it
// only verifies the hashes and revisions the result carries. Build output must stay
// in sync with the creator bundle, so both run the same complete rule set.
const result = await build({
  entryPoints: [fileURLToPath(new URL('../src/utils/ejs-checker/review-worker.mjs', import.meta.url))],
  bundle: true, write: false, format: 'iife', platform: 'browser', target: 'es2022', minify: true,
  legalComments: 'none',
  banner: { js: '// Generated by cloudflare/scripts/build-review-checker.mjs. Licenses: /assets/upload-checker-notices.txt' },
});
const source = result.outputFiles[0].text;
const directory = new URL('../src/generated/', import.meta.url);
await fs.mkdir(directory, { recursive: true });
await fs.writeFile(new URL('review-checker.txt', directory), Buffer.from(source, 'utf8').toString('base64'));
await fs.writeFile(new URL('review-checker-revision.json', directory), JSON.stringify({ revision: createHash('sha256').update(source).digest('hex').slice(0, 20) }) + '\n');
console.log('Built browser review checker from the shared v2 parser and L-series rules.');
