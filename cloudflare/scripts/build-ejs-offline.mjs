import {build} from 'esbuild';
import fs from 'node:fs/promises';
import {fileURLToPath} from 'node:url';

const entry=new URL('../src/utils/ejs-checker/browser.mjs',import.meta.url);
const outfile=new URL('../../util/ejs-checker-v2.js',import.meta.url);
const noticeFiles=['EJS-NOTICE.txt','EJS-LICENSE.txt','THIRD-PARTY-NOTICES.txt'];
const notices=await Promise.all(noticeFiles.map(name=>fs.readFile(new URL('../src/utils/ejs-checker/vendor/'+name,import.meta.url),'utf8')));
await fs.writeFile(new URL('../../util/ejs-checker-v2.NOTICES.txt',import.meta.url),notices.join('\n\n'));
await build({entryPoints:[fileURLToPath(entry)],outfile:fileURLToPath(outfile),bundle:true,format:'iife',globalName:'PoemEjsChecker',platform:'browser',target:'es2022',legalComments:'none',banner:{js:'// Generated by cloudflare/scripts/build-ejs-offline.mjs. Licenses: ejs-checker-v2.NOTICES.txt'}});
console.log('Built offline checker from the same v2 modules used by the Worker.');
